import fs from "node:fs";
import path from "node:path";
import { PROJECT_MANIFEST_FILE, readProjectManifest } from "../project-manifest.js";
import { getRecipe, getTemplate } from "../registry/index.js";
import { listRecipeFiles } from "../scaffold/inventory.js";
import { getManifestAdapter } from "../scaffold/manifest.js";
import { KIT_VERSION } from "../scaffold/paths.js";
import { validateAgentConfiguration } from "../scaffold/validate-output.js";

export type ProjectCheckStatus = "ok" | "warn" | "fail" | "info";

export type ProjectCheck = {
  id: "manifest" | "kit-version" | "agent-docs" | "recipe-files" | "env" | "dependencies";
  status: ProjectCheckStatus;
  message: string;
  /** Command or action that resolves the finding. */
  fix?: string;
};

export type ProjectReport = {
  dir: string;
  /** False when the directory has no `zealakit.json` (all other checks skipped). */
  isZealakitProject: boolean;
  checks: ProjectCheck[];
};

/** Compare `1.0.0-beta.4` style versions; negative when `a` is older than `b`. */
export function compareKitVersions(a: string, b: string): number {
  const parse = (version: string) => {
    const [core = "", pre = ""] = version.split("-", 2);
    const numbers = core.split(".").map((part) => Number.parseInt(part, 10) || 0);
    const preParts = pre ? pre.split(".") : [];
    return { numbers, preParts };
  };
  const left = parse(a);
  const right = parse(b);
  for (let i = 0; i < 3; i += 1) {
    const diff = (left.numbers[i] ?? 0) - (right.numbers[i] ?? 0);
    if (diff !== 0) return diff;
  }
  // A release outranks any of its prereleases.
  if (left.preParts.length === 0 && right.preParts.length === 0) return 0;
  if (left.preParts.length === 0) return 1;
  if (right.preParts.length === 0) return -1;
  for (let i = 0; i < Math.max(left.preParts.length, right.preParts.length); i += 1) {
    const x = left.preParts[i];
    const y = right.preParts[i];
    if (x === undefined) return -1;
    if (y === undefined) return 1;
    const nx = Number(x);
    const ny = Number(y);
    const diff = Number.isNaN(nx) || Number.isNaN(ny) ? x.localeCompare(y) : nx - ny;
    if (diff !== 0) return diff;
  }
  return 0;
}

function envKeys(file: string): string[] {
  return fs
    .readFileSync(file, "utf-8")
    .split(/\r?\n/)
    .map((line) => /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(line)?.[1])
    .filter((key): key is string => key !== undefined);
}

function tryAdapter(ecosystem: string) {
  try {
    return getManifestAdapter(ecosystem as never);
  } catch {
    return undefined;
  }
}

export type CheckProjectOptions = {
  /** Package manager used for the suggested install command. */
  installCommand?: string;
};

/** Health checks for a generated project directory. Never throws. */
export function checkProject(dir: string, options: CheckProjectOptions = {}): ProjectReport {
  const root = path.resolve(dir);
  const checks: ProjectCheck[] = [];
  const loaded = readProjectManifest(root);
  if (!loaded) {
    return { dir: root, isZealakitProject: false, checks };
  }
  if (!loaded.ok) {
    checks.push({
      id: "manifest",
      status: "fail",
      message: loaded.errors.join(" "),
      fix: `Fix ${PROJECT_MANIFEST_FILE} (schema: schema/zealakit.schema.json).`,
    });
    return { dir: root, isZealakitProject: true, checks };
  }
  const { manifest } = loaded;
  checks.push({
    id: "manifest",
    status: "ok",
    message: `${PROJECT_MANIFEST_FILE}: ${manifest.template} + ${manifest.recipes.length} recipe(s).`,
  });

  const cmp = compareKitVersions(manifest.kitVersion, KIT_VERSION);
  checks.push(
    cmp > 0
      ? {
          id: "kit-version",
          status: "warn",
          message: `Project was generated by zealakit ${manifest.kitVersion}, newer than the installed ${KIT_VERSION}.`,
          fix: "npx zealakit@latest …",
        }
      : {
          id: "kit-version",
          status: "ok",
          message: `Generated by zealakit ${manifest.kitVersion} (installed ${KIT_VERSION}).`,
        },
  );

  const agentErrors: string[] = [];
  validateAgentConfiguration(root, agentErrors);
  checks.push(
    agentErrors.length > 0
      ? {
          id: "agent-docs",
          status: "fail",
          message: agentErrors.join(" "),
          fix: "ln -sfn .agents .cursor",
        }
      : { id: "agent-docs", status: "ok", message: "Agent docs layout is intact." },
  );

  const template = getTemplate(manifest.template);
  if (!template) {
    checks.push({
      id: "recipe-files",
      status: "warn",
      message: `Template '${manifest.template}' is not known to this zealakit version; recipe files were not checked.`,
    });
  } else {
    const missing: string[] = [];
    for (const recipeId of manifest.recipes) {
      if (!getRecipe(recipeId)) continue;
      try {
        for (const relative of listRecipeFiles(recipeId, template.id, template).keys()) {
          if (relative.includes("/.gitkeep") || relative === ".gitkeep") continue;
          if (
            !fs.existsSync(path.join(root, relative)) &&
            !fs.existsSync(path.join(root, relative.replace(/\/_gitignore$/, "/.gitignore")))
          ) {
            missing.push(`${recipeId}: ${relative}`);
          }
        }
      } catch {
        // A recipe without an overlay for this template contributes no files.
      }
    }
    checks.push(
      missing.length > 0
        ? {
            id: "recipe-files",
            status: "warn",
            message: `${missing.length} recipe file(s) missing (removed on purpose?): ${missing.slice(0, 5).join(", ")}${missing.length > 5 ? ", …" : ""}`,
          }
        : { id: "recipe-files", status: "ok", message: "All recipe files are present." },
    );
  }

  const example = path.join(root, ".env.example");
  if (fs.existsSync(example)) {
    const env = path.join(root, ".env");
    if (!fs.existsSync(env)) {
      checks.push({
        id: "env",
        status: "warn",
        message: ".env.example exists but .env does not.",
        fix: "cp .env.example .env",
      });
    } else {
      const have = new Set(envKeys(env));
      const missing = envKeys(example).filter((key) => !have.has(key));
      checks.push(
        missing.length > 0
          ? {
              id: "env",
              status: "warn",
              message: `.env is missing: ${missing.join(", ")}.`,
              fix: "Add the missing keys from .env.example.",
            }
          : { id: "env", status: "ok", message: ".env has every key from .env.example." },
      );
    }
  }

  const adapterStatus = tryAdapter(manifest.ecosystem)?.dependencyStatus?.(root);
  if (adapterStatus) {
    checks.push({
      id: "dependencies",
      status: adapterStatus.ok ? "ok" : "info",
      message: adapterStatus.message,
      ...(adapterStatus.fix ? { fix: adapterStatus.fix } : {}),
    });
  } else if (manifest.ecosystem === "go") {
    const hasSum = fs.existsSync(path.join(root, "go.sum"));
    checks.push(
      hasSum
        ? { id: "dependencies", status: "ok", message: "go.sum present." }
        : { id: "dependencies", status: "info", message: "go.sum is missing.", fix: "go mod tidy" },
    );
  } else {
    const installed = fs.existsSync(path.join(root, "node_modules"));
    checks.push(
      installed
        ? { id: "dependencies", status: "ok", message: "node_modules present." }
        : {
            id: "dependencies",
            status: "info",
            message: "node_modules is missing.",
            fix: options.installCommand ?? "npm install",
          },
    );
  }

  return { dir: root, isZealakitProject: true, checks };
}
